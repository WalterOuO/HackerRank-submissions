def minimumDistances(a):
    # Write your code here
    seen = {}
    diff = len(a)
    for i, val in enumerate(a):
        if val not in seen:
            seen[val] = i
        else:
            diff = min(diff, abs(i - seen[val]))

    return -1 if diff == len(a) else diff

